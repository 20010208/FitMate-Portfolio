export type Locale = 'en' | 'ja'
export type TranslationKey = keyof typeof translations.en

// FitMateは<html lang="ja">・全metadata・記事とも日本語専用のアプリのため、ロケールは
// 常に'ja'に固定する。以前はnavigator.languageでサーバー('en'固定、navigator未定義のため)
// とクライアント(実ブラウザ言語)の判定を分けており、日本語ブラウザでは初回hydration時に
// テキストが'en'→'ja'へ食い違い、React hydration error #418の原因になっていた。
export function getLocale(): Locale {
  return 'ja'
}

export function useT() {
  const locale = getLocale()
  return (key: TranslationKey) => translations[locale][key]
}

export function getT(locale: Locale) {
  return (key: TranslationKey) => translations[locale][key]
}
